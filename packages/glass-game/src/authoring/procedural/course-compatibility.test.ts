// Fixed v1 sharing contracts — prevent an existing code from silently changing its route or save identity.

import { createHash } from 'node:crypto'
import { describe, expect, it } from 'vitest'
import { generateProceduralCourse } from './course-generator.ts'
import { decodeProceduralCourseCode, encodeProceduralCourseCode, PROCEDURAL_COURSE_VERSION, } from './course-options.ts'
import fixture from './fixtures/course-v1.compatibility.json'

function signature(value: unknown): string {
  // Object field order is not part of the course contract. Array order and
  // exact numeric values are: they affect route selection, motion and saves.
  const canonical = JSON.stringify(value, (_key, item: unknown) => {
    if (item === null || typeof item !== 'object' || Array.isArray(item))
      return item
    return Object.fromEntries(
      Object.entries(item).sort(([a], [b]) => (a < b ? -1 : a > b ? 1 : 0)),
    )
  })
  return createHash('sha256').update(canonical).digest('hex')
}

describe('previously shared v1 courses', () => {
  it('keeps the reviewed generator contract until a compatible version dispatcher exists', () => {
    expect(PROCEDURAL_COURSE_VERSION).toBe(fixture.generatorVersion)
    expect(fixture.generatorVersion).toBe(1)
    expect(fixture.courses).toHaveLength(16)
  })

  it.each(fixture.courses)(
    'recreates the fixed $label code and route',
    (saved) => {
      // These are literal codes and signatures captured from the reviewed head,
      // not expectations generated by the implementation under test. Do not
      // refresh them for a route change: retain v1 and introduce a new version.
      const options = decodeProceduralCourseCode(saved.code)
      const course = generateProceduralCourse(options)
      expect(encodeProceduralCourseCode(options)).toBe(saved.code)
      expect(course.courseId).toBe(saved.courseId)
      expect(course.compiledLevel.id).toBe(saved.courseId)
      expect(course.compiledLevel.platforms).toHaveLength(saved.platforms)
      expect(course.compiledLevel.checkpoints).toHaveLength(saved.checkpoints)
      expect(signature(course.rawDocument)).toBe(saved.rawSha256)
      // The compiler's profiles and defaults are part of compatibility too.
      expect(signature(course.compiledLevel)).toBe(saved.compiledSha256)
    },
  )
})
