// Length + letter + number only — no uppercase/special-char composition
// rules. Browser password generators must always pass (Firefox generates
// letters+digits with no specials), and NIST 800-63B favours length over
// composition anyway. Mirrored client-side in src/lib/password-policy.ts —
// keep the two in sync.
function isStrongPassword(password: string): { ok: boolean; reason?: string } {
  if (password.length < PASSWORD_MIN_LENGTH) {
    return {
      ok: false,
      reason: `Password must be at least ${PASSWORD_MIN_LENGTH} characters`,
    }
  }
  if (!/[A-Za-z]/.test(password)) {
    return { ok: false, reason: 'Password must contain at least one letter' }
  }
  if (!/[0-9]/.test(password)) {
    return { ok: false, reason: 'Password must contain at least one number' }
  }
  return { ok: true }
}

const encoder = new TextEncoder()

/** A JWT segment is base64url and nothing else. Same shape check the
 *  background-capability verifier already applies before decoding. */
const SEGMENT_RE = /^[A-Za-z0-9_-]+$/

// ── base64url helpers ────────────────────────────────────────────────

function b64urlEncode(data: ArrayBuffer | Uint8Array): string {
  const bytes = data instanceof Uint8Array ? data : new Uint8Array(data)
  let bin = ''
  for (const b of bytes) bin += String.fromCharCode(b)
  return btoa(bin).replace(/\+/g, '-').replace(/\//g, '_').replace(/=+$/, '')
}

function b64urlDecode(s: string): Uint8Array {
  const pad = s.length % 4 === 0 ? '' : '='.repeat(4 - (s.length % 4))
  const bin = atob(s.replace(/-/g, '+').replace(/_/g, '/') + pad)
  return Uint8Array.from(bin, (c) => c.charCodeAt(0))
}

// ── JWT (HS256) ──────────────────────────────────────────────────────

async function hmacKey(secret: string): Promise<CryptoKey> {
  return crypto.subtle.importKey(
    'raw',
    encoder.encode(secret),
    { name: 'HMAC', hash: 'SHA-256' },
    false,
    ['sign', 'verify'],
  )
}

export interface JwtPayload {
  sub: string
  provider: string
  iat: number
  exp: number
  v: number
  /** `authSessions.id` — absent on tokens issued before migration 0038. */
  sid?: string
}

/** Exported for the integration test that mints a pre-0038 token (no `sid`). */
export async function signJwt(
  payload: JwtPayload,
  secret: string,
): Promise<string> {
  const header = b64urlEncode(
    encoder.encode(JSON.stringify({ alg: 'HS256', typ: 'JWT' })),
  )
  const body = b64urlEncode(encoder.encode(JSON.stringify(payload)))
  const data = `${header}.${body}`
  const sig = await crypto.subtle.sign(
    'HMAC',
    await hmacKey(secret),
    encoder.encode(data),
  )
  return `${data}.${b64urlEncode(sig)}`
}

async function verifyJwt(
  token: string,
  secret: string,
): Promise<JwtPayload | null> {
  const parts = token.split('.')
  if (parts.length !== 3) return null
  const [header, body, sig] = parts
  // Every segment must decode before anything is verified. `b64urlDecode`
  // wraps `atob`, which THROWS on a segment that is not base64url or whose
  // length % 4 === 1 — and this call used to sit outside the try below, so a
  // malformed signature escaped as a DOMException instead of returning null.
  // `getAuth` runs on the common path for every request, so that exception
  // unwound to the top-level handler and answered 500 on EVERY endpoint,
  // including `/api/auth/me`. A client that stored such a token could never
  // recover on its own: 5xx is treated as a server hiccup and the token is
  // kept, so no 401 ever arrived to clear it. A malformed credential must be
  // indistinguishable from a wrong one — both are 401.
  if (
    !SEGMENT_RE.test(header) ||
    !SEGMENT_RE.test(body) ||
    !SEGMENT_RE.test(sig)
  )
    return null
  let valid: boolean
  try {
    valid = await crypto.subtle.verify(
      'HMAC',
      await hmacKey(secret),
      b64urlDecode(sig),
      encoder.encode(`${header}.${body}`),
    )
  } catch {
    return null
  }
  if (!valid) return null
  try {
    const payload = JSON.parse(
      new TextDecoder().decode(b64urlDecode(body)),
    ) as JwtPayload
    if (typeof payload.sub !== 'string' || typeof payload.exp !== 'number')
      return null
    if (payload.exp < Math.floor(Date.now() / 1000)) return null
    return payload
  } catch {
    return null
  }
}

/** Extract and verify the Bearer token. Returns null when absent/invalid. */
export async function getAuth(
  request: Request,
  env: Env,
): Promise<AuthUser | null> {
  if (!env.JWT_SECRET) return null
  const header = request.headers.get('Authorization')
  if (!header?.startsWith('Bearer ')) return null
  const payload = await verifyJwt(header.slice(7), env.JWT_SECRET)
  if (!payload) return null

  // Fail closed: the user must still exist, and a token whose version is below
  // the stored tokenVersion was revoked (logout, etc.). A missing `v` claim is
  // treated as version 0 so a single tokenVersion bump also revokes legacy
  // tokens.
  const user = await env.DB.prepare(
    'SELECT tokenVersion, lastActiveAt, suspendedAt, email FROM users WHERE id = ?',
  )
    .bind(payload.sub)
    .first<{
      tokenVersion: number
      lastActiveAt: string | null
      suspendedAt: string | null
      email: string | null
    }>()
  if (!user) return null
  // Check this before tokenVersion: suspension bumps that counter too, but the
  // client needs the distinct 403 to avoid silently minting a replacement
  // anonymous identity. Once restored, the old token falls through to the
  // ordinary version check and stays revoked.
  assertAccountActive(user)
  const testAccount = await managedStateForIdentity(
    env.DB,
    payload.sub,
    user.email,
  )
  assertManagedTestAccountActive(testAccount)
  if (user.tokenVersion > (payload.v ?? 0)) return null

  // Which device this is. A token minted before migration 0038 carries no
  // `sid`, and is deliberately still accepted — a hard cutover would sign
  // every singer out of an app they were using at the time. A token that DOES
  // name a session and finds no row was signed out on that device, so it fails
  // closed, exactly like a revoked tokenVersion.
  if (payload.sid !== undefined) {
    if (!(await sessionAlive(env.DB, payload.sid, payload.sub))) return null
    // Fire-and-forget, and conditional in SQL: an idle-ish session costs one
    // write per SESSION_TOUCH_SECONDS rather than one per request, and a
    // failed touch must never fail the request that carried it.
    try {
      await touchSession(env.DB, payload.sid)
    } catch {
      // Ignore: "when we last saw this device" is best-effort.
    }
  }

  // Throttled last-active touch: at most one write per user per window (see
  // shouldTouchLastActive), so ongoing visits are tracked without multiplying
  // D1 writes. Awaited inside try/catch on purpose: a best-effort tracking
  // write must never fail auth, and — since getAuth has no ExecutionContext to
  // waitUntil() — must not be a dangling promise the runtime can cancel once
  // the response is returned.
  if (shouldTouchLastActive(user.lastActiveAt, Date.now())) {
    try {
      await env.DB.prepare('UPDATE users SET lastActiveAt = ? WHERE id = ?')
        .bind(new Date().toISOString(), payload.sub)
        .run()
    } catch {
      // Ignore: last-active tracking is best-effort.
    }
  }

  return {
    userId: payload.sub,
    provider: payload.provider,
    ...(payload.sid === undefined ? {} : { sessionId: payload.sid }),
    isTestAccount: testAccount !== null,
    testAccountExpiresAt: testAccount?.expiresAt ?? null,
  }
}

// ── Password hashing (PBKDF2-SHA256) ─────────────────────────────────

async function pbkdf2(
  password: string,
  salt: Uint8Array,
  iterations: number,
): Promise<ArrayBuffer> {
  const key = await crypto.subtle.importKey(
    'raw',
    encoder.encode(password),
    'PBKDF2',
    false,
    ['deriveBits'],
  )
  return crypto.subtle.deriveBits(
    { name: 'PBKDF2', hash: 'SHA-256', salt: salt as BufferSource, iterations },
    key,
    256,
  )
}

export async function hashPassword(password: string): Promise<string> {
  const salt = crypto.getRandomValues(new Uint8Array(16))
  const bits = await pbkdf2(password, salt, PBKDF2_ITERATIONS)
  return `pbkdf2$${PBKDF2_ITERATIONS}$${b64urlEncode(salt)}$${b64urlEncode(bits)}`
}

async function verifyPassword(
  password: string,
  stored: string,
): Promise<boolean> {
  const [scheme, iters, saltB64, hashB64] = stored.split('$')
  if (scheme !== 'pbkdf2') return false
  const bits = new Uint8Array(
    await pbkdf2(password, b64urlDecode(saltB64), Number(iters)),
  )
  const expected = b64urlDecode(hashB64)
  if (bits.length !== expected.length) return false
  let diff = 0
  for (let i = 0; i < bits.length; i++) diff |= bits[i] ^ expected[i]
  return diff === 0
}

/**
 * Constant-time string comparison for secrets (admin keys, tokens). Unlike
 * `===`, it never short-circuits on the first differing byte, so the time
 * taken does not leak how many leading bytes a guess got right. A length
 * mismatch is folded into the result rather than returned early.
 */
export function timingSafeEqual(a: string, b: string): boolean {
  const ab = encoder.encode(a)
  const bb = encoder.encode(b)
  let diff = ab.length ^ bb.length
  for (let i = 0; i < ab.length; i++) diff |= ab[i] ^ (bb[i] ?? 0)
  return diff === 0
}

// ── Google ID-token verification ─────────────────────────────────────

interface GoogleClaims {
  aud: string
  sub: string
  email?: string
  email_verified?: string
  name?: string
  picture?: string
}

async function verifyGoogleIdToken(
  idToken: string,
  clientId: string,
): Promise<GoogleClaims | null> {
  // Use the v3 tokeninfo endpoint (POST body, not query param — avoids
  // token leakage in intermediate proxy/server logs).
  const res = await fetch('https://www.googleapis.com/oauth2/v3/tokeninfo', {
    method: 'POST',
    headers: { 'Content-Type': 'application/x-www-form-urlencoded' },
    body: new URLSearchParams({ id_token: idToken }),
  })
  if (!res.ok) return null
  const claims = await res.json<GoogleClaims>()
  if (claims.aud !== clientId) return null
  return claims
}

