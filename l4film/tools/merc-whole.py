#!/usr/bin/env python3
"""Each Merc pass's first whole frame, for the kit's entrance gate (PRODUCTION-PIPELINE trap 23).

  python3 tools/merc-whole.py            writes assets/merc/whole.js and prints the table
  python3 tools/merc-whole.py --check    exit 1 if whole.js is missing a rendered pass or is stale

A pass whose first state is `drop` comes in through the top of its square: its first frames hold
only part of the body. Its first whole frame is the first, after the body has touched the square's
top three rows, with those rows empty again in alpha (> 8 of 255). A pass that starts in any other
state is whole from frame 0 and gets 0. L.mercGate (assets/lib/hosts.js) reads window.MERC_WHOLE
and opens one frame later. Only passes whose WebM is rendered and newer than its shot file count.
Builder A's lab/s04-recall/scratch/whole.py is the same test; it gave m06a-orange 30.
"""
import glob
import json
import os
import subprocess
import sys

import numpy as np

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
OUT = os.path.join(ROOT, 'assets', 'merc', 'whole.js')
FRAMES = 90  # a drop is over in 0.55 s (33 frames at 60 fps)


def first_whole(webm):
    w, h = (int(v) for v in subprocess.run(
        ['ffprobe', '-v', 'error', '-select_streams', 'v:0', '-show_entries', 'stream=width,height', '-of', 'csv=p=0', webm],
        check=True, capture_output=True, text=True).stdout.strip().split(','))
    raw = subprocess.run(
        ['ffmpeg', '-loglevel', 'error', '-c:v', 'libvpx-vp9', '-i', webm, '-frames:v', str(FRAMES), '-vf', 'format=rgba',
         '-f', 'rawvideo', '-'], check=True, capture_output=True).stdout
    frames = np.frombuffer(raw, np.uint8).reshape(-1, h, w, 4)
    touched = False
    for i, f in enumerate(frames):
        top = int((f[:3, :, 3] > 8).sum())
        if top > 0:
            touched = True
        elif touched:
            return i
    return None


def table():
    out = {}
    for shot in sorted(glob.glob(os.path.join(ROOT, 'merc', 'shots', '*.json'))):
        d = json.load(open(shot))
        webm = os.path.join(ROOT, 'assets', 'merc', d['id'] + '-merc.webm')
        if not os.path.exists(webm) or os.path.getmtime(webm) < os.path.getmtime(shot):
            continue
        drops = bool(d['cues']) and d['cues'][0]['state'] == 'drop'
        out[d['id']] = first_whole(webm) if drops else 0
    return out


def render(t):
    return ('// Generated by tools/merc-whole.py from the rendered Merc passes. Do not edit.\n'
            '// Each pass: the first frame of its drop with the whole body inside its square, or 0 (no drop).\n'
            'window.MERC_WHOLE = ' + json.dumps(t, indent=1, sort_keys=True) + ';\n')


def main():
    t = table()
    bad = [k for k, v in t.items() if v is None]
    if '--check' in sys.argv:
        ok = os.path.exists(OUT) and open(OUT).read() == render(t) and not bad
        print('whole.js current' if ok else 'whole.js stale or missing: run python3 tools/merc-whole.py')
        sys.exit(0 if ok else 1)
    for k in bad:
        print(f'{k}: the body never left the top rows in {FRAMES} frames; left out', file=sys.stderr)
        del t[k]
    open(OUT, 'w').write(render(t))
    for k, v in sorted(t.items()):
        print(f'{k:14s} {v if v else "0 (no drop)"}')
    print(f'{len(t)} passes in {os.path.relpath(OUT, ROOT)}')


if __name__ == '__main__':
    main()
