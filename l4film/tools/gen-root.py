"""Generate the root composition and the scene table from cues.json.

  python3 tools/gen-root.py

Writes assets/scenes.js (window.SCENES: each scene's start and end on the film
clock, cut at cue boundaries) and index.html (one host per scene, the
soundtrack). Scene files live in compositions/<id>.html and are written by
hand; a scene with no file yet gets a placeholder card so the film always
renders end to end. A placeholder is rewritten on every run until a builder
replaces it, and takes its length from the table at run time (L.dur), so no
scene file ever holds a typed second. In a built scene the one generated
number, its root data-duration, is kept equal to the table.
"""
import json, os, re

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(HERE)
cues = json.load(open(os.path.join(ROOT, 'cues.json')))
C, TOTAL = cues['cues'], cues['total']

# scene id, first cue (its start is the cut), title for the placeholder
SCENES = [
    ('s01-cold-open', None, 'Cold open: seven stairs, one short of home'),
    ('s02-title', 'title', 'Title'),
    ('s03-promise', 'b3', 'The promise'),
    ('s04-recall', 'b4', 'From Lesson 2: twelve semitones, seven steps'),
    ('s05-steps', 'act1', 'Count the steps'),
    ('s06-groups', 'o5', 'Two groups and a joint'),
    ('s07-predict', 'act2', 'Predict: the white keys from D'),
    ('s08-anywhere', 'o8', 'A pattern, not a set of keys'),
    ('s09-names', 'act3', 'Name the stairs'),
    ('s10-ti', 'b32', 'Ti, one short of home'),
    ('s11-why', 'o10', 'Why do is home'),
    ('s12-sing', 'act4', 'Sing it: Merc, then Tavi'),
    ('s13-your-turn', 'b41', 'Your turn'),
    ('s14-recap', 'recap', 'Quick check'),
    ('s15-next', 'next', 'Next time'),
    ('s16-end', 'end', 'End card'),
]


def main():
    starts = []
    for sid, cue, title in SCENES:
        t = 0.0 if cue is None else C[cue]['start']
        # cut a little before a mark so the whoosh and the move lead the voice
        if cue in ('act1', 'act2', 'act3', 'act4', 'recap', 'next'):
            t = C[cue]['start'] - 0.15
        starts.append(round(t, 3))
    scenes = {}
    for i, (sid, cue, title) in enumerate(SCENES):
        end = starts[i + 1] if i + 1 < len(SCENES) else TOTAL
        scenes[sid] = {'start': starts[i], 'end': round(end, 3), 'title': title}
    with open(os.path.join(ROOT, 'assets/scenes.js'), 'w') as f:
        f.write('// Generated by tools/gen-root.py from cues.json. Do not edit.\n')
        f.write('window.SCENES = ' + json.dumps(scenes, indent=1) + ';\n')

    os.makedirs(os.path.join(ROOT, 'compositions'), exist_ok=True)
    hosts = []
    synced = []
    for sid, s in scenes.items():
        path = os.path.join(ROOT, 'compositions', sid + '.html')
        dur = f"{s['end'] - s['start']:.3f}"
        holder = PLACEHOLDER.replace('__ID__', sid).replace('__TITLE__', s['title']).replace('__DUR__', dur)
        if not os.path.exists(path) or (f'>PLACEHOLDER · {sid}<' in open(path).read() and open(path).read() != holder):
            # no scene yet, or a placeholder from an older run: write the current placeholder
            with open(path, 'w') as f:
                f.write(holder)
        else:
            # a re-voice re-times the scenes: keep each scene's own data-duration equal to the table
            html = open(path).read()
            pat = re.compile(r'(<div\b[^>]*\bdata-composition-id="' + re.escape(sid) + r'"[^>]*\bdata-duration=")([\d.]+)(")')
            m = pat.search(html)
            if m and m.group(2) != dur:
                open(path, 'w').write(html[:m.start()] + m.group(1) + dur + m.group(3) + html[m.end():])
                synced.append(f'{sid} {m.group(2)} -> {dur}')
        hosts.append(
            f'      <div id="host-{sid}" class="clip" data-composition-id="{sid}" data-composition-src="compositions/{sid}.html" '
            f'data-start="{s["start"]:.3f}" data-duration="{s["end"] - s["start"]:.3f}"></div>'
        )
    fonts = open(os.path.join(ROOT, 'assets/lib/fonts.css.txt')).read()
    html = ROOT_HTML.replace('__SCRIPTS__', scripts_html()).replace('__FONTS__', fonts).replace('__HOSTS__', '\n'.join(hosts)).replace('__TOTAL__', f'{TOTAL:.3f}').replace('__AUDIO__', os.environ.get('MIX', 'full'))
    with open(os.path.join(ROOT, 'index.html'), 'w') as f:
        f.write(html)
    for sid, s in scenes.items():
        print(f"{sid:18s} {s['start']:7.2f} - {s['end']:7.2f}  ({s['end'] - s['start']:5.2f}s)")
    for line in synced:
        print('data-duration updated:', line)


def scripts_html():
    """One <script> per line of assets/lib/scripts.txt: the kit, in load order."""
    paths = [l.strip() for l in open(os.path.join(ROOT, 'assets/lib/scripts.txt')) if l.strip() and not l.startswith('#')]
    return '\n'.join(f'    <script src="{p}"></script>' for p in paths)


ROOT_HTML = '''<!doctype html>
<!-- Find Your Pitch, Lesson 4: The major scale and home. Generated by tools/gen-root.py. -->
<html lang="en">
  <head>
    <meta charset="UTF-8" />
    <meta name="viewport" content="width=1920, height=1080" />
__SCRIPTS__
    <link rel="stylesheet" href="assets/lib/lesson.css" />
    <style>
__FONTS__
    </style>
  </head>
  <body>
    <div id="root" data-composition-id="main" data-start="0" data-duration="__TOTAL__" data-width="1920" data-height="1080">
__HOSTS__
      <audio id="soundtrack" src="assets/audio/__AUDIO__.wav" data-start="0" data-duration="__TOTAL__" data-volume="1"></audio>
    </div>
    <script>
      const tl = gsap.timeline({ paused: true })
      tl.set({}, {}, __TOTAL__)
      window.__timelines = window.__timelines || {}
      window.__timelines['main'] = tl
    </script>
  </body>
</html>
'''

PLACEHOLDER = '''<!doctype html>
<html lang="en">
  <head><meta charset="UTF-8" /></head>
  <body>
    <div id="__ID__" data-composition-id="__ID__" data-start="0" data-duration="__DUR__" data-width="1920" data-height="1080">
      <div class="scene">
        <div class="ground" data-layout-allow-overflow></div>
        <div class="staves" data-layout-allow-overflow></div>
        <p class="kicker" style="left:120px;top:120px">PLACEHOLDER · __ID__</p>
        <p class="serif" style="position:absolute;left:120px;top:440px;font-size:120px">__TITLE__</p>
      </div>
      <script>
        ;(function () {
          const tl = gsap.timeline({ paused: true })
          tl.fromTo('#__ID__ .serif', { x: 0 }, { x: 60, duration: L.dur('__ID__'), ease: 'none' }, 0)
          window.__timelines = window.__timelines || {}
          window.__timelines['__ID__'] = tl
        })()
      </script>
    </div>
  </body>
</html>
'''

if __name__ == '__main__':
    main()
