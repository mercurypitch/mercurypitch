// Stamp every social card with the hash of its own bytes.
//
// Discord, Slack, WhatsApp and the rest cache an Open Graph image against its
// URL, for days or weeks, and no purge of ours reaches them. Regenerating
// `guitar-night-og.png` in place therefore leaves every link ever shared
// showing the old art — which is exactly what happened after the 2026-09-10
// card refresh: the room had gained Free play and the shared card still
// offered "I know my way around".
//
// So the URL carries the art's own fingerprint: change the picture, change the
// link, and the next scrape fetches the new one. Run this after regenerating
// any card; `src/tests/og-image-cache-busting.test.ts` fails the build when the
// stamp and the file disagree.
//
//   node scripts/gen-og-versions.mjs

import { createHash } from 'node:crypto'
import { readdirSync, readFileSync, writeFileSync } from 'node:fs'
import { dirname, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'

const REPO = resolve(dirname(fileURLToPath(import.meta.url)), '..')
const PUBLIC = resolve(REPO, 'public')
const OUT = resolve(REPO, 'src/seo/og-image-versions.ts')

/** Social cards: the shared one, every `*-og.png`, and Glass's own jpg. */
export function ogImageFiles() {
  const root = readdirSync(PUBLIC)
    .filter((name) => name === 'og-image.png' || /-og\.png$/.test(name))
    .sort()
  const glass = readdirSync(resolve(PUBLIC, 'glass'))
    .filter((name) => /^og\.(png|jpe?g)$/.test(name))
    .map((name) => `glass/${name}`)
  return [...root, ...glass]
}

/** Eight hex characters of the file's SHA-256: enough to never collide here. */
export function ogImageVersion(file) {
  return createHash('sha256')
    .update(readFileSync(resolve(PUBLIC, file)))
    .digest('hex')
    .slice(0, 8)
}

export function ogImageVersions() {
  return Object.fromEntries(
    ogImageFiles().map((file) => [file, ogImageVersion(file)]),
  )
}

function render(versions) {
  const rows = Object.entries(versions)
    .map(([file, hash]) => `  '${file}': '${hash}',`)
    .join('\n')
  return `// Generated by scripts/gen-og-versions.mjs — do not edit by hand.
//
// Eight hex characters of each card's SHA-256, spent as a \`?v=\` on its public
// URL so a regenerated card is a new link to every social cache. Regenerate a
// card, run the script, commit both.

export const OG_IMAGE_VERSIONS: Readonly<Record<string, string>> = {
${rows}
}
`
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  writeFileSync(OUT, render(ogImageVersions()))
  console.log(
    `og versions: ${Object.keys(ogImageVersions()).length} cards stamped`,
  )
}
