// ============================================================
// Preview DB — challenge / badge / achievement definition seed
// ============================================================
//
// PR previews bind to their own `mercurypitch-db-preview` database (see
// wrangler.pr-preview.template.jsonc), which starts with nothing in it
// but the migration chain. Only the weekly-challenge fixture was seeded,
// so the Challenges tab came up completely empty on every preview: no
// challenge cards, every category counter reading 0, no badges and no
// achievements. That is not a bug anyone can see through — it looks
// exactly like a broken feature, and it hid a real badge-rendering fix
// from review.
//
// Dev and production get these rows from scripts/seed-remote-db.mjs,
// which talks to the worker's admin API. CI has no admin key — it has a
// Cloudflare token and `wrangler d1 execute` — so this emits the same
// content as SQL instead. Same source of truth either way:
// src/db/seed-data.json.
//
// Usage:
//   node scripts/gen-preview-definitions-sql.mjs > preview-definitions.sql

import seedData from '../src/db/seed-data.json' with { type: 'json' }

/**
 * A fixed timestamp, not "now". The preview database is shared between
 * concurrent PR runs, so a moving value would rewrite every row on every
 * build and make the seed churn instead of settle.
 */
const STAMP = '2026-01-01T00:00:00.000Z'

/** Deterministic id from the row's natural key, so re-runs are no-ops. */
export function seedId(prefix, naturalKey) {
  const slug = naturalKey
    .toLowerCase()
    .normalize('NFKD')
    .replace(/[^a-z0-9]+/g, '-')
    .replace(/^-|-$/g, '')
  return `seed-${prefix}-${slug}`
}

export function sqlValue(v) {
  if (v === null || v === undefined) return 'NULL'
  if (typeof v === 'boolean') return v ? '1' : '0'
  if (typeof v === 'number') return String(v)
  return `'${String(v).replace(/'/g, "''")}'`
}

/**
 * One idempotent upsert per row.
 *
 * ON CONFLICT updates the content columns but leaves the id alone, so
 * per-user progress rows that point at a definition stay attached — the
 * same guarantee the admin-API seeder makes.
 */
export function buildStatements(data = seedData) {
  const tables = [
    ['challengeDefinitions', 'challenge', 'title', data.challengeDefinitions],
    ['badgeDefinitions', 'badge', 'name', data.badgeDefinitions],
    ['achievements', 'achievement', 'name', data.achievementDefinitions],
  ]

  const out = []
  for (const [table, prefix, keyField, rows] of tables) {
    // One column list for the whole table, not per row. Rows omit optional
    // fields (not every challenge grants a badge); without the union, a
    // field dropped from seed-data.json would keep its old value forever
    // because the upsert would never name that column.
    const cols = ['id', 'createdAt', 'updatedAt']
    for (const row of rows) {
      for (const k of Object.keys(row)) if (!cols.includes(k)) cols.push(k)
    }
    for (const row of rows) {
      const full = {
        id: seedId(prefix, row[keyField]),
        createdAt: STAMP,
        updatedAt: STAMP,
        ...Object.fromEntries(cols.slice(3).map((c) => [c, row[c] ?? null])),
      }
      const values = cols.map((c) => sqlValue(full[c]))
      // createdAt is not in the update list: a row that already exists
      // keeps the moment it was first seeded.
      const updates = cols
        .filter((c) => c !== 'id' && c !== 'createdAt')
        .map((c) => `${c} = excluded.${c}`)
      out.push(
        `INSERT INTO ${table} (${cols.join(', ')})\n` +
          `VALUES (${values.join(', ')})\n` +
          `ON CONFLICT(id) DO UPDATE SET ${updates.join(', ')};`,
      )
    }
  }
  return out
}

export function buildSql(data = seedData) {
  const statements = buildStatements(data)
  return (
    '-- Generated by scripts/gen-preview-definitions-sql.mjs — do not edit.\n' +
    '-- Source of truth: src/db/seed-data.json\n' +
    `-- ${statements.length} definition rows.\n\n` +
    `${statements.join('\n\n')}\n`
  )
}

// Only write when run directly, so the tests can import the builders.
if (process.argv[1]?.endsWith('gen-preview-definitions-sql.mjs')) {
  process.stdout.write(buildSql())
}
