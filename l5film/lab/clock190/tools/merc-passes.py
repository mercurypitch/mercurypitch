"""Write merc/PASSES.md, the scene builders' guide to Merc's passes: every pass and chunk (file,
frames, size, the cues it covers, its render), the moments a scene carries (leaps, hops), where the
feet sit in a pass's frame (measured from the rendered frames), and how a scene places, scales and
mirrors a pass.

  python3 tools/merc-passes.py

Reads merc/shots/*.json, the sidecars (and their roots, which tools/merc-roots.py writes to assets/merc/roots.js) assets/merc/<out>-merc.json (from merc-pass.mjs), the dumped
frames in lab/merc/dump/ (the feet), cues.json and assets/scenes.js. Run it after the passes render,
and again after every re-render (the 60 fps passes too).
"""
import glob
import json
import os
import statistics

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(HERE)
CUES = json.load(open(os.path.join(ROOT, 'cues.json')))
C = CUES['cues']
_sj = open(os.path.join(ROOT, 'assets/scenes.js')).read()
SC = json.loads(_sj[_sj.index('=') + 1:].strip().rstrip(';'))
PX_PER_UNIT = 0.4353   # shown px per world unit, per px of the shown frame's width (front view, at the floor)


def fmt(t):
    return f'{int(t // 60)}:{t % 60:05.2f}'


def covered(a, b):
    """The events (cues.json) that a film span [a, b) touches, in order."""
    return [k for k, v in sorted(C.items(), key=lambda kv: kv[1]['start']) if v['start'] < b and max(v['end'], v['start'] + 1e-6) > a]


def side(out_id):
    p = os.path.join(ROOT, 'assets', 'merc', out_id + '-merc.json')
    return json.load(open(p)) if os.path.exists(p) else None


def feet():
    """Measured from every dumped frame whose root is at rest: the lowest opaque row (alpha >= 128),
    the body's opaque columns, as fractions of the frame, by drawn size."""
    by = {}
    for path in glob.glob(os.path.join(ROOT, 'lab', 'merc', 'dump', '*.rgba')):
        stem = os.path.basename(path)[:-5]
        out_id, f = stem.rsplit('-f', 1)
        s = side(out_id)
        if not s or s['root'][int(f) - s['from']] != [0, 0]:
            continue
        w, h = s['drawn']
        b = open(path, 'rb').read()
        rows = [y for y in range(h) if any(b[(y * w + x) * 4 + 3] >= 128 for x in range(w))]
        cols = [x for x in range(w) if any(b[(y * w + x) * 4 + 3] >= 250 for y in range(h))]
        if rows and cols:
            by.setdefault(w, []).append(((rows[-1] + 1) / h, rows[0] / h, (cols[0] + cols[-1] + 1) / 2 / w))
    return by


def sole_line(fb=None):
    """The feet line a scene uses: the median nearer-sole row over every measured frame, 3 decimals."""
    fb = feet() if fb is None else fb
    v = [x[0] for frames in fb.values() for x in frames]
    return round(statistics.median(v), 3) if v else 0.83


def main():
    shots = [json.load(open(p)) for p in sorted(glob.glob(os.path.join(ROOT, 'merc', 'shots', '*.json')))]
    shots.sort(key=lambda s: (s['filmStart'], s['id']))
    L = []
    w = L.append
    w('# Merc\'s passes: a guide for the scene builders')
    w('')
    w('Generated by `tools/merc-passes.py` from the shot files (`merc/shots/`, written by')
    w('`tools/merc-shots.py` from the cues), the passes\' sidecars (`assets/merc/<file>-merc.json`, written')
    w('by `tools/merc-pass.mjs`) and their dumped frames. Do not edit; re-run it after every render.')
    w('The decisions behind it: DECISIONS 128 to 131 and 160 to 163.')
    w('')
    w('## The passes')
    w('')
    w('Three performances (STORYBOARD § Merc performances). Every pass is a straight-alpha VP9 WebM at')
    w('the pass\'s fps, its drawn square three quarters of its `size` (`medium`): 225 px for 300, 300 for')
    w('400, 315 for 420. Pass frame i is film frame round(filmStart x fps) + i exactly. These are 30 fps')
    w('passes on the scratch clock; the final 60 fps passes come after the final voices.')
    w('')
    w('| Pass | Host | Film span | Frames | Rendered at | Mirror in the scene | Files |')
    w('| ---- | ---- | --------- | ------ | ----------- | ------------------- | ----- |')
    for s in shots:
        n = round(s['duration'] * s['fps'])
        files = f"{len(s['chunks'])} chunks, below" if s.get('chunks') else f"`assets/merc/{s['id']}-merc.webm`"
        sizes = sorted({c['size'] for c in s.get('chunks', [])} or {s['size']})
        w(f"| {s['id']} | {'Merc' if s['variant'] == 'blue' else 'Tavi'} | {s['filmStart']:.3f} to {s['filmStart'] + s['duration']:.3f} "
          f"({fmt(s['filmStart'])} to {fmt(s['filmStart'] + s['duration'])}) | {n} at {s['fps']} fps | {' and '.join(map(str, sizes))} | "
          f"{'yes, scaleX(-1)' if s.get('mirror') else 'no'} | {files} |")
    w('')
    w('## Chunks and renders')
    w('')
    w('m-orange and m-blue are cut at every scene boundary: one chunk a scene, from one frame before the')
    w('scene to two after it, so neighbours share three frames (the join proof compares them,')
    w('`review/merc/joins.md`). `tools/merc-tags.py` gives each scene its own chunk. "Cues" are the first')
    w('and last events of `cues.json` the chunk\'s frames touch. Times a frame are the render\'s own,')
    w('with another heavy job sharing the machine.')
    w('')
    w('| File (`assets/merc/`) | Scene | Pass frames | Film time | Size (drawn) | Cues | Frames | Time a frame | Render |')
    w('| --------------------- | ----- | ----------- | --------- | ------------ | ---- | ------ | ------------ | ------ |')
    total_frames = total_s = 0
    for s in shots:
        fps = s['fps']
        parts = s.get('chunks') or [{'id': s['id'], 'scene': 's01-cold-open', 'from': 0, 'to': round(s['duration'] * fps) - 1, 'size': s['size']}]
        for c in parts:
            a = s['filmStart'] + c['from'] / fps
            b = s['filmStart'] + (c['to'] + 1) / fps
            cv = covered(a, b)
            sd = side(c['id'])
            n = c['to'] - c['from'] + 1
            drawn = round(c['size'] * 0.75)
            if sd:
                total_frames += sd['frames']
                total_s += sd['renderSeconds']
            w(f"| {c['id']}-merc.webm | {c['scene']} | {c['from']} to {c['to']} | {a:.3f} to {b:.3f} | {c['size']} ({drawn}) | "
              f"{cv[0]} to {cv[-1]} | {n} | {str(sd['msPerFrame']) + ' ms' if sd else 'not rendered'} | "
              f"{str(round(sd['renderSeconds'] / 60, 1)) + ' min' if sd else '-'} |")
    w('')
    w(f'Rendered: {total_frames} frames (the shared frames counted in both chunks) in {total_s / 3600:.2f} hours of rendering.')
    w('')
    w('## Moments a scene carries')
    w('')
    w('The renderer performs these in place; the scene moves the box (STORYBOARD and HANDOFFS § Entrances')
    w('and moves). Film times on the voiced clock; "air" is when the host is off the floor.')
    w('')
    w('| Pass | Moment | State | Film start | Air | Pass frame | Chunk | The scene |')
    w('| ---- | ------ | ----- | ---------- | --- | ---------- | ----- | --------- |')
    what = {
        ('m-orange', 0): ('leap in', 'carries her in from 300 px beyond the right edge to (1800, 840) while she is in the air'),
        ('m-orange', 1): ('hop left (end card)', 'carries her 190 px left to (1610, 840) in the air, growing 300 to 400 about the feet from the jump\'s start over 0.70 s'),
        ('m-blue', 0): ('leap in', 'carries him in from 300 px beyond the left edge to (110, 840) while he is in the air'),
        ('m-blue', 1): ('hop 1 (the `card` pause)', 'carries him (110, 840) to (700, 840) through the air, power1.in, cancelling the renderer\'s root (below)'),
        ('m-blue', 2): ('hop 2 (the `card` pause)', 'carries him (700, 840) to (1290, 840) through the air, power1.in, cancelling the renderer\'s root (below)'),
    }
    for s in shots:
        k = 0
        for i, c in enumerate(s['cues']):
            if c['state'] not in ('celebrate', 'hop'):
                continue
            t = s['filmStart'] + c['t']
            air = (t + 0.15, t + 0.58) if c['state'] == 'celebrate' else (t + 0.12, t + 0.53)
            f = round(c['t'] * s['fps'])
            ch = next((x['id'] for x in s.get('chunks', []) if x['from'] <= f <= x['to'] and x['scene'] in [sid for sid, v in SC.items() if v['start'] <= t < v['end']]), s['id'])
            name, how = what.get((s['id'], k), (c['state'], ''))
            w(f"| {s['id']} | {name} | `{c['state']}` | {t:.3f} | {air[0]:.3f} to {air[1]:.3f} | {f} | {ch} | {how} |")
            k += 1
    w('')
    w('Merc\'s hops are in the `card` pause, the first silence after b55 that holds them (DECISIONS 160):')
    w('he stands in his corner, (110, 840), through b55, b56 and b58, and hops only after b58 ends. On')
    w('the board, "Ten minutes, gently, most days." / "Missed a day? Just come back." stand under the')
    w('Voice Mirror card at baselines 822 and 862 from x 230 to about 800 (13f), on his path at the')
    w('floor: S13 must clear them, or the lead re-places them, before he hops. The hops draw their dotted')
    w('arc and echo trail but no floor stop marks (DECISIONS 162).')
    w('')
    w('## What the hosts do')
    w('')
    w('- Talk on their own lines (mouth by the line\'s loudness, sound arcs at half strength).')
    w('- Sing their own sounds: Merc `gauge`, `listen` (A3) and `twinkle`; Tavi `demo` (on the page\'s')
    w('  demo line, to the cent) and `listen` (A4); full sound arcs.')
    w('- Listen to the other\'s lines: the renderer\'s `listen` (one eye closed, leaning toward the')
    w('  speaker, no arcs) for the first 3 s of each line (the whole line if shorter), then `idle`, eyes')
    w('  open and held on the speaker, until the line ends (DECISIONS 161).')
    w('- Idle, turned to the drawing, through every sound neither makes (easy, pushed, push, the starts,')
    w('  starts, the other\'s sounds), the pauses, and the viewer\'s breathe, ticks and hold: no arcs.')
    w('')
    # feet
    fb = feet()
    F = sole_line(fb)
    w('## Where the feet sit in a pass\'s frame')
    w('')
    if fb:
        w('Measured on every dumped frame with the root at rest (lab/merc/dump/), as a fraction of the')
        w('frame\'s height from its top (the lowest row with alpha 128 or more: the nearer foot\'s sole) and')
        w('of its width (the middle of the opaque body):')
        w('')
        w('| Drawn square | Frames | Sole, lowest row (min to max) | Body top (alpha 128) | Body centre, x |')
        w('| ------------ | ------ | ----------------------------- | -------------------- | -------------- |')
        for dw in sorted(fb):
            v = fb[dw]
            soles = [x[0] for x in v]
            w(f"| {dw} px | {len(v)} | {statistics.median(soles):.3f} ({min(soles):.3f} to {max(soles):.3f}) | "
              f"{statistics.median(x[1] for x in v):.3f} | {statistics.median(x[2] for x in v):.3f} |")
        w('')
    w('Both hosts render facing screen right with the same camera (`front`), so both have the same')
    w(f'feet: **the feet line is {F:.3f} of the frame\'s height** (the median nearer sole above; it moves')
    w('by about one drawn pixel with the pose), the farther foot\'s sole about 0.02 higher (perspective:')
    w('the body is turned 0.32 rad), and the body is centred at **0.500** of the width. The floor under')
    w('the body\'s centre (the root, y 0) projects to 0.789; the soles sit below it because the feet')
    w('stand in front of the root.')
    w('')
    w('## Placing a pass in a scene')
    w('')
    w('- **The tag.** A static `<video id="<scene>-<pass>" data-merc="<pass>" class="clip" muted playsinline>`')
    w('  in the scene, `data-merc` the pass id (`m-blue`, never a chunk id); `python3 tools/merc-tags.py')
    w('  <scene>` writes its `src` (the scene\'s own chunk), `data-start`, `data-duration` and')
    w('  `data-media-start`. A reflection tag beside it carries `data-merc-refl` (trap 4).')
    w('- **The box.** Show the video in a square box of side S (CSS px), the frame filling it (the video')
    w('  is square). S is the shown size: 300 in the corners, 240 small (S6 to S9), 400 on the end card,')
    w('  420 in S1. A chunk is rendered at the largest S its scene uses, so a scene only ever scales a')
    w('  pass down (S6 to S9 show 300 renders at 240), never up.')
    w(f'- **Standing on y 840.** With the feet point at (x, 840): `left = x - 0.5 S`, `top = 840 - {F:.3f} S`')
    w('  (' + '; '.join(f'{S}: top {840 - F * S:.1f}' for S in (300, 240, 400, 420)) + '). Scale the box about the')
    w(f'  feet point, `transform-origin: 50% {F * 100:.1f}%`, so a size change in place keeps the feet on the')
    w('  floor. The body box HANDOFFS gives (0.53 S wide, 0.64 S tall above the feet) is the opaque body')
    w('  and its glow.')
    w('- **Mirroring Tavi.** Every one of Tavi\'s passes (m01-orange, m-orange) is shown with `scaleX(-1)`')
    w('  about the box\'s vertical centre line (on the video, or with the origin above); the feet point')
    w('  stays at 0.5 S, so nothing else changes. Merc\'s passes are never mirrored (his hops go right).')
    w('- **The reflection.** The same frame flipped about the feet line, y 840 on screen (`scaleY(-1)`')
    w(f'  about {F * 100:.1f} % of the box), at 16 % (HANDOFFS § The floor).')
    w('- **Root motion.** The renderer moves Merc\'s root during a hop: x from 0 to +0.38 world units')
    w('  through the air (49.6 px at S 300: 0.4353 x S px a unit; the feet measured 35 to 39 drawn px')
    w('  on a landed hop against 37.2), held until the next hop snaps it back to 0, then after the second')
    w('  hop eased back to 0 over about half a second. A scene that carries him itself cancels it: on each')
    w('  frame, shift the box by `-root[i][0] x 0.4353 x S` px (the opposite sign on a mirrored pass), frame')
    w('  i counted from the chunk\'s first frame. Then the box\'s path is the scene\'s own tween, and he lands')
    w('  exactly on (700, 840) and (1290, 840). The root\'s y is the jump itself (leaps, hops, the end')
    w('  card): leave it. Only the hops move a root\'s x: m-blue-s13 is the one chunk whose x moves; every')
    w('  other chunk\'s x is 0 on every frame (only `hop` sets the root\'s x in the renderer; the leaps')
    w('  and the end-card hop are jumps in place, y only), so an all-zero table is right, not missing.')
    w('- **The root table, for the hosts layer.** `assets/merc/roots.js` (written by `tools/merc-roots.py`')
    w('  from the sidecars) sets `window.MERC_ROOTS`, one entry a chunk keyed by its id (the file\'s name;')
    w('  the chunk `tools/merc-tags.py` gives scene `sNN-...` is `<pass>-sNN`; m01-blue and m01-orange')
    w('  are keyed by the pass): `{ frames: [[x, y], ...], t0, fps }`, `t0` the film time of `frames[0]`.')
    w('  It loads after `assets/scenes.js` and before the scenes (the lead adds it to `scripts.txt`). A')
    w('  scene passes its own chunk\'s entry to the hosts layer:')
    w('')
    w('  ```js')
    w("  L.mercGate(layer, { sid: 's13-recap', pass: 'm-blue', tag: 's13-recap-m-blue', x: 110, size: 300,")
    w("    moves: [/* the two hops' carries, power1.in */], root: window.MERC_ROOTS['m-blue-s13'] })")
    w('  ```')
    w('')
    w('  Passing it in every scene is harmless (all zeros cancel nothing); only S13\'s Merc needs it.')
    w('- **Leaps.** Each long pass starts on its leap (`celebrate`, frame 0). Until the scene carries the')
    w('  box in, it is off frame: Tavi from beyond the right edge, Merc from beyond the left; both land')
    w('  in their corners 0.80 s before their first word (HANDOFFS: `leapDx` 300 px, the carry in the air).')
    w('- **Size changes and moves** are the scene\'s, in screen space (the passes never change size).')
    w('- **Timing.** A 30 fps pass in the 60 fps master shows each pass frame on two film frames; the')
    w('  tags are on the pass\'s frame grid: 60 fps film frame n shows pass frame floor(n / 2) - P, P the')
    w('  pass\'s first frame on the 30 fps grid (round(filmStart x 30)).')
    w('- **The sidecar** (`assets/merc/<file>-merc.json`): `from`, `to`, `frames`, `fps`, `filmStart`,')
    w('  `size`, `drawn`, the render\'s `msPerFrame`, `renderSeconds` and `prerollSeconds`, `crescentFixed`')
    w('  (frames the crescent guard re-rendered, trap 10), the `pin` (Chromium, Playwright, the bundle\'s')
    w('  sha256 and commit) and `root`, one [x, y] a frame.')
    w('')
    path = os.path.join(ROOT, 'merc', 'PASSES.md')
    open(path, 'w').write('\n'.join(L) + '\n')
    print(f'merc/PASSES.md written ({total_frames} frames rendered)')


if __name__ == '__main__':
    main()
