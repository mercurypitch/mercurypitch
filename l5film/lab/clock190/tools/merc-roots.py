"""Write assets/merc/roots.js: every rendered chunk's renderer root, for the scenes' hosts layer.

  python3 tools/merc-roots.py            writes assets/merc/roots.js and prints each chunk's root range

    window.MERC_ROOTS = { '<chunk id>': { frames: [[x, y], ...], t0, fps }, ... }

One entry a chunk (m-blue-s13, m-orange-s06, ...) and one a pass without chunks (m01-blue,
m01-orange), named as its file (assets/merc/<id>-merc.webm) and as tools/merc-tags.py names the
chunk it gives a scene: a pass's chunk for scene sNN-... is `<pass>-sNN`. `frames` is the sidecar's
`root`, Merc's root [x, y] in world units on each frame of the chunk (the renderer's uRoot); `t0` is
the film time of frames[0] (filmStart + from / fps, to 9 decimals, so a frame index taken from film
time never rounds a frame early); `fps` the pass's. L.mercGate({ root: MERC_ROOTS['m-blue-s13'] })
(assets/lib/hosts.js) cancels the x, 0.4353 x the shown size px a world unit (merc/PASSES.md).

Only Merc's hops move a root's x (m-blue-s13: 0 to +0.38 a hop, back to 0 after). The leaps and
Tavi's end-card hop are `celebrate` jumps in place, which move only y; every other state holds the
root at [0, 0], so an idle, talking, listening or singing chunk's frames are all zeros, and that is
right. Run after every render (tools/merc-queue.py's chunks); a chunk not rendered yet is left out.
"""
import glob
import json
import os

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(HERE)


def main():
    out = {}
    rows = []
    for path in sorted(glob.glob(os.path.join(ROOT, 'merc', 'shots', '*.json'))):
        shot = json.load(open(path))
        fps = shot['fps']
        P = round(shot['filmStart'] * fps)
        parts = shot.get('chunks') or [{'id': shot['id'], 'from': 0, 'to': round(shot['duration'] * fps) - 1}]
        for c in parts:
            sp = os.path.join(ROOT, 'assets', 'merc', c['id'] + '-merc.json')
            if not os.path.exists(sp):
                rows.append(f"{c['id']:14s} not rendered")
                continue
            side = json.load(open(sp))
            assert side['from'] == c['from'] and side['to'] == c['to'] and side['fps'] == fps, c['id']
            fr = side['root']
            assert len(fr) == c['to'] - c['from'] + 1 and all(f is not None for f in fr), c['id']
            out[c['id']] = {'t0': round((P + c['from']) / fps, 9), 'fps': fps, 'frames': fr}
            xs = [f[0] for f in fr]
            ys = [f[1] for f in fr]
            moving = [i for i, x in enumerate(xs) if abs(x) > 1e-4]
            rows.append(f"{c['id']:14s} {len(fr):5d} frames  x {min(xs):+.4f} to {max(xs):+.4f}  y {min(ys):+.4f} to {max(ys):+.4f}"
                        + (f"  x moves on {len(moving)} frames, film {out[c['id']]['t0'] + moving[0] / fps:.3f} to "
                           f"{out[c['id']]['t0'] + moving[-1] / fps:.3f}" if moving else '  x at rest throughout'))
    body = json.dumps(out, separators=(',', ':'))
    js = ('// Generated by tools/merc-roots.py from the chunks\' sidecars. Do not edit.\n'
          '// Each chunk\'s renderer root [x, y] a frame, t0 the film time of frames[0] (merc/PASSES.md).\n'
          'window.MERC_ROOTS = ' + body + ';\n')
    path = os.path.join(ROOT, 'assets', 'merc', 'roots.js')
    open(path, 'w').write(js)
    print('\n'.join(rows))
    print(f'assets/merc/roots.js: {len(out)} chunks, {len(js) // 1024} KB')


if __name__ == '__main__':
    main()
