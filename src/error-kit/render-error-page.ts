// Renders an error state to the static document that ships for it.
//
// The not-found state is 404.html, which the asset layer answers every
// unmatched path with (wrangler.jsonc, not_found_handling). It is a page, not
// an app shell: no #root, no module script, nothing to boot, so it paints
// the moment its one stylesheet arrives. What it says is error-states.ts,
// what it shows is staves.ts, and the room links come from the same model
// every entry document's nav does, so a new room is linked here too.

// Relative, not '@/': vite.config.ts loads this file through
// tools/generate-error-pages.ts, before the alias exists.
import { LEGAL_DOCUMENT_LINKS } from '../lib/legal-links'
import { DEFAULT_THEME_COLOR, navLinksFor } from '../seo/entry-pages'
import { esc } from '../seo/render-entry-page'
import type { ErrorState } from './error-states'
import { ERROR_STATES } from './error-states'
import { staveSvg } from './staves'

export interface RenderErrorPageOptions {
  /** Entries this build serves but does not advertise; never linked. */
  unlisted?: readonly string[]
  /** The released lessons, linked after Home as on every entry. */
  lessons?: readonly { href: string; label: string }[]
}

/** A tuner's dial with its needle hard over: the tag's little picture. */
const GAUGE =
  '<svg class="error-scene__gauge" viewBox="0 0 28 16" aria-hidden="true" focusable="false"><path d="M3 14a11 11 0 0 1 22 0" /><line x1="14" y1="3" x2="14" y2="6" /><line x1="14" y1="14" x2="23.5" y2="7" /><circle cx="14" cy="14" r="1.6" /></svg>'

export function renderErrorPage(
  state: ErrorState,
  options: RenderErrorPageOptions = {},
): string {
  const copy = ERROR_STATES[state]
  const nav = navLinksFor(null, options.unlisted, options.lessons)
    .map(
      (link) => `          <a href="${esc(link.href)}">${esc(link.label)}</a>`,
    )
    .join('\n')
  const legalNav = LEGAL_DOCUMENT_LINKS.map(
    (link) => `        <a href="${esc(link.href)}">${esc(link.label)}</a>`,
  ).join('\n')

  return `<!doctype html>
<!-- Generated by tools/generate-error-pages.ts from src/error-kit/. Edit those, not this file. -->
<html lang="en">
  <head>
    <meta charset="UTF-8" />
    <meta
      name="viewport"
      content="width=device-width, initial-scale=1.0, viewport-fit=cover"
    />
    <title>${esc(copy.title)}</title>
    <meta name="description" content="${esc(copy.description)}" />
    <!-- The status code is what a crawler acts on; this is the belt-and-braces
         for the day a misconfiguration serves this document with a 200. \`follow\`
         on purpose, so the links out are still crawled. -->
    <meta name="robots" content="noindex, follow" />
    <!-- Deliberately no canonical: a page that does not exist must not claim to
         be a copy of one that does. -->
    <link rel="icon" href="/favicon.ico" sizes="48x48" />
    <link rel="icon" type="image/svg+xml" href="/favicon.svg" />
    <meta name="theme-color" content="${DEFAULT_THEME_COLOR}" />
    <link rel="stylesheet" href="/src/styles/error-scene.css" />
  </head>
  <body>
    <main class="error-scene" data-state="${state}">
      ${staveSvg(state)}
      <div class="error-scene__card">
        <div class="error-scene__lockup">
          <img src="/brand-mark.svg" width="44" height="44" alt="MercuryPitch" />
          <span class="error-scene__wordmark" aria-hidden="true">Mercury<span>Pitch</span></span>
        </div>
        <p class="error-scene__tag">${GAUGE}<span>${esc(copy.tag)}</span></p>
        <h1>${esc(copy.heading)}</h1>
        <p class="error-scene__line">${esc(copy.line)}</p>
        <a class="error-scene__primary" href="${esc(copy.primary.href)}">${esc(copy.primary.label)}</a>
        <nav aria-label="More from MercuryPitch">
${nav}
        </nav>
      </div>
      <nav class="error-scene__legal" aria-label="Legal">
${legalNav}
      </nav>
    </main>
  </body>
</html>
`
}
