import { readFileSync } from 'node:fs'
import { resolve } from 'node:path'
import { describe, expect, it } from 'vitest'
import { ERROR_STATES } from '@/error-kit/error-states'
import { renderErrorPage } from '@/error-kit/render-error-page'
import { staveSvg } from '@/error-kit/staves'
import { LEGAL_DOCUMENT_LINKS } from '@/lib/legal-links'
import { ABOUT_URL, canonicalPath, ENTRY_PAGES } from '@/seo/entry-pages'

// The error pages are the scene in docs/plans/error-pages.md: a static
// document per failure, from src/error-kit/. These hold what the plan asks
// of every one of them: a page and not an app, the words from one place,
// every room linked from the same model the entries use, the picture as
// decoration only, and stillness for a visitor who asks for it.

const repo = resolve(__dirname, '../..')
const parse = (html: string) =>
  new DOMParser().parseFromString(html, 'text/html')

describe('the not-found page', () => {
  const document = parse(renderErrorPage('not-found'))
  const copy = ERROR_STATES['not-found']

  it('is a page, not an app: no root, no script, one stylesheet', () => {
    expect(document.querySelector('#root')).toBeNull()
    expect(document.querySelectorAll('script')).toHaveLength(0)
    const sheets = [...document.querySelectorAll('link[rel="stylesheet"]')]
    expect(sheets.map((sheet) => sheet.getAttribute('href'))).toEqual([
      '/src/styles/error-scene.css',
    ])
  })

  it('says what error-states.ts says, under one heading', () => {
    expect(document.title).toBe(copy.title)
    expect(document.querySelectorAll('h1')).toHaveLength(1)
    expect(document.querySelector('h1')?.textContent).toBe(copy.heading)
    expect(document.querySelector('.error-scene__tag')?.textContent).toBe(
      copy.tag,
    )
    expect(document.querySelector('.error-scene__line')?.textContent).toBe(
      copy.line,
    )
    const primary = document.querySelector('.error-scene__primary')
    expect(primary?.getAttribute('href')).toBe(copy.primary.href)
    expect(primary?.textContent).toBe(copy.primary.label)
  })

  it('stays out of the index, and claims to be no other page', () => {
    expect(
      document.querySelector('meta[name="robots"]')?.getAttribute('content'),
    ).toBe('noindex, follow')
    expect(document.querySelector('link[rel="canonical"]')).toBeNull()
  })

  it('links every room from the model, Home first and About last', () => {
    const hrefs = [
      ...document.querySelectorAll(
        'nav[aria-label="More from MercuryPitch"] a',
      ),
    ].map((a) => a.getAttribute('href'))
    expect(hrefs[0]).toBe('/')
    expect(hrefs.at(-1)).toBe(ABOUT_URL)
    for (const page of ENTRY_PAGES) {
      expect(hrefs, page.slug).toContain(canonicalPath(page))
    }
  })

  it('leaves an unlisted room out', () => {
    const unlisted = parse(
      renderErrorPage('not-found', { unlisted: ['glass-game'] }),
    )
    const hrefs = [...unlisted.querySelectorAll('nav a')].map((a) =>
      a.getAttribute('href'),
    )
    expect(hrefs).not.toContain('/glass-game')
    expect(hrefs).toContain('/glass')
  })

  it('closes on the legal links', () => {
    const hrefs = [
      ...document.querySelectorAll('nav[aria-label="Legal"] a'),
    ].map((a) => a.getAttribute('href'))
    expect(hrefs).toEqual(LEGAL_DOCUMENT_LINKS.map((link) => link.href))
  })

  it('draws its pictures as decoration, and names its one image', () => {
    for (const svg of document.querySelectorAll('svg')) {
      expect(svg.getAttribute('aria-hidden')).toBe('true')
      expect(svg.getAttribute('focusable')).toBe('false')
    }
    for (const image of document.querySelectorAll('img')) {
      expect(image.getAttribute('alt')).toBeTruthy()
    }
  })
})

describe('the staves', () => {
  it.each(Object.keys(ERROR_STATES) as (keyof typeof ERROR_STATES)[])(
    'draws %s with ids that cannot meet another page’s',
    (state) => {
      const svg = parse(staveSvg(state)).querySelector('svg')
      expect(svg?.getAttribute('data-state')).toBe(state)
      for (const node of svg?.querySelectorAll('[id]') ?? []) {
        expect(node.id).toMatch(/^es-/)
      }
    },
  )
})

describe('the scene stylesheet', () => {
  const css = readFileSync(resolve(repo, 'src/styles/error-scene.css'), 'utf8')

  it('holds still for a visitor who asks for less motion', () => {
    const reduced = css.slice(
      css.indexOf('@media (prefers-reduced-motion: reduce)'),
    )
    expect(reduced).toContain('.error-scene__drift')
    expect(reduced).toContain('.error-scene__glide')
    expect(reduced).toContain('animation: none')
  })
})

describe('the generated 404.html', () => {
  it('is the kit’s not-found page, written by the generator', () => {
    const file = readFileSync(resolve(repo, '404.html'), 'utf8')
    expect(file).toContain('Generated by tools/generate-error-pages.ts')
    expect(file).toContain(staveSvg('not-found'))
  })
})
